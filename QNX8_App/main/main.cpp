#include <iostream>

using namespace std;

int main() {
    // Hello World Program
    cout << "Hello World!" << endl;
    
    // Addition Program
    int a = 10;
    int b = 20;
    int sum = a + b;
    cout << "Addition: " << a << " + " << b << " = " << sum << endl;
    
    // Subtraction Program
    int difference = a - b;
    cout << "Subtraction: " << a << " - " << b << " = " << difference << endl;
    
    return 0;
}
